CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    username TEXT NOT NULL CHECK (username <> '' AND username = btrim(username)),
    email TEXT NOT NULL CHECK (email <> '' AND email = btrim(email))
);

CREATE UNIQUE INDEX users_username_normalized_key ON users (lower(username));
CREATE UNIQUE INDEX users_email_normalized_key ON users (lower(email));

CREATE TABLE user_interactions (
    user_id BIGINT NOT NULL REFERENCES users (id),
    reel_id BIGINT NOT NULL REFERENCES reels (id),
    kind TEXT NOT NULL CHECK (kind IN ('like', 'save', 'view')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    view_date DATE,
    CHECK ((kind = 'view') = (view_date IS NOT NULL))
);

CREATE UNIQUE INDEX user_interactions_active_key
    ON user_interactions (user_id, reel_id, kind) WHERE kind IN ('like', 'save');
CREATE UNIQUE INDEX user_interactions_daily_view_key
    ON user_interactions (user_id, reel_id, view_date) WHERE kind = 'view';

CREATE TABLE reel_shares (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY CHECK (id > 0),
    sender_id BIGINT NOT NULL REFERENCES users (id),
    recipient_id BIGINT NOT NULL REFERENCES users (id),
    reel_id BIGINT NOT NULL REFERENCES reels (id),
    idempotency_key TEXT NOT NULL CHECK (idempotency_key COLLATE "C" ~ '^[A-Za-z0-9._~-]{1,128}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (sender_id, idempotency_key),
    CHECK (sender_id <> recipient_id)
);

CREATE TABLE user_reel_watch_sessions (
    user_id BIGINT NOT NULL REFERENCES users (id),
    reel_id BIGINT NOT NULL REFERENCES reels (id),
    playback_id TEXT NOT NULL CHECK (playback_id COLLATE "C" ~ '^[A-Za-z0-9._~-]{1,128}$'),
    watched_ms BIGINT NOT NULL CHECK (watched_ms >= 0),
    PRIMARY KEY (user_id, playback_id)
);

