CREATE TABLE creators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    display_name TEXT NOT NULL
);

CREATE TABLE reels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    creator_id BIGINT NOT NULL REFERENCES creators (id),
    caption TEXT NOT NULL,
    video_url TEXT NOT NULL,
    thumbnail_url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived'))
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    title TEXT NOT NULL,
    brand TEXT NOT NULL,
    image_url TEXT NOT NULL,
    price BIGINT NOT NULL CHECK (price >= 0),
    category TEXT NOT NULL CHECK (category ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

COMMENT ON COLUMN products.price IS 'Price in USD cents';

CREATE TABLE reel_products (
    reel_id BIGINT NOT NULL REFERENCES reels (id),
    product_id BIGINT NOT NULL REFERENCES products (id),
    display_position INTEGER NOT NULL CHECK (display_position >= 0),
    PRIMARY KEY (reel_id, product_id)
);

CREATE INDEX reel_products_display_order_idx
    ON reel_products (reel_id, display_position, product_id);

